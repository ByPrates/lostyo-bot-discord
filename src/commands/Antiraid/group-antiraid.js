const handlers = {
    "antiraid": async (client, interaction) => {
        const locale = resolveLocale({ guildId: interaction.guildId, discordLocale: interaction.locale });
        const state = interaction.options.getString('state', true) === 'on';
        client.database.set('antiraid-' + interaction.guildId, state);
        return interaction.reply({ embeds: [successEmbed(locale, t('antiraid.ok', { locale, vars: { state: state ? 'on' : 'off' } }) + ' TODO: join-rate engine.')] });
    },
    "join-gate": async (client, interaction) => {
        const locale = resolveLocale({ guildId: interaction.guildId, discordLocale: interaction.locale });
        const days = interaction.options.getInteger('days', true);
        client.database.set('joingate-' + interaction.guildId, days);
        return interaction.reply({ embeds: [successEmbed(locale, t('joingate.ok', { locale, vars: { days } }) + ' TODO: enforce on join.')] });
    },
    "panic": async (client, interaction) => {
        const locale = resolveLocale({ guildId: interaction.guildId, discordLocale: interaction.locale });
        if (interaction.user.id !== interaction.guild.ownerId) return interaction.reply({ embeds: [errorEmbed(locale, t('handler.not_guild_owner', { locale }))], ephemeral: true });
        const state = interaction.options.getString('state', true);
        const val = state === 'on' ? false : null;
        for (const [, ch] of interaction.guild.channels.cache.filter(c => c.isTextBased() && !c.isThread())) {
            try { await ch.permissionOverwrites.edit(interaction.guild.roles.everyone, { SendMessages: val }); } catch {}
        }
        for (const [, ch] of interaction.guild.channels.cache.filter(c => c.isVoiceBased())) {
            try { await ch.permissionOverwrites.edit(interaction.guild.roles.everyone, { Connect: state === 'on' ? false : null }); } catch {}
        }
        return interaction.reply({ embeds: [successEmbed(locale, t('panic.ok', { locale, vars: { state } }))] });
    },
    "quarantine": async (client, interaction) => {
        const locale = resolveLocale({ guildId: interaction.guildId, discordLocale: interaction.locale });
        const user = interaction.options.getUser('user', true);
        const member = await interaction.guild.members.fetch(user.id).catch(() => null);
        if (!member) return interaction.reply({ embeds: [errorEmbed(locale, t('common.member_not_found', { locale }))], ephemeral: true });
        let role = interaction.guild.roles.cache.find(r => r.name === 'Quarantine');
        if (!role) { try { role = await interaction.guild.roles.create({ name: 'Quarantine' }); } catch (e) { return interaction.reply({ embeds: [errorEmbed(locale, t('mod_error', { locale, vars: { error: e.message || e } }))], ephemeral: true }); } }
        try { await member.roles.add(role); } catch (e) { return interaction.reply({ embeds: [errorEmbed(locale, t('mod_error', { locale, vars: { error: e.message || e } }))], ephemeral: true }); }
        return interaction.reply({ embeds: [successEmbed(locale, t('quarantine.on', { locale, vars: { user: user.tag } }))] });
    },
    "unquarantine": async (client, interaction) => {
        const locale = resolveLocale({ guildId: interaction.guildId, discordLocale: interaction.locale });
        const user = interaction.options.getUser('user', true);
        const member = await interaction.guild.members.fetch(user.id).catch(() => null);
        if (!member) return interaction.reply({ embeds: [errorEmbed(locale, t('common.member_not_found', { locale }))], ephemeral: true });
        let role = interaction.guild.roles.cache.find(r => r.name === 'Quarantine');
        if (!role) return interaction.reply({ embeds: [errorEmbed(locale, t('quarantine.norole', { locale }))], ephemeral: true });
        try { await member.roles.remove(role); } catch (e) { return interaction.reply({ embeds: [errorEmbed(locale, t('mod_error', { locale, vars: { error: e.message || e } }))], ephemeral: true }); }
        return interaction.reply({ embeds: [successEmbed(locale, t('quarantine.off', { locale, vars: { user: user.tag } }))] });
    },
    "verify-setup": async (client, interaction) => {
        const locale = resolveLocale({ guildId: interaction.guildId, discordLocale: interaction.locale });
        const role = interaction.options.getRole('role', true);
        const ch = interaction.options.getChannel('channel') || interaction.channel;
        client.database.set('verify-' + interaction.guildId, { role: role.id, channel: ch.id });
        if (ch.isTextBased()) await ch.send(t('verify.msg', { locale }) + ' (TODO: button engine.)');
        return interaction.reply({ embeds: [successEmbed(locale, t('verify.ok', { locale }))] });
    },
};


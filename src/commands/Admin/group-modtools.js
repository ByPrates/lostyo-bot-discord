        const locale = resolveLocale({ guildId: interaction.guildId, discordLocale: interaction.locale });
        const modstore = require('../../utils/modstore');
        const user = interaction.options.getUser('user', true);
        const reason = interaction.options.getString('reason') || 'No reason';
        const rec = modstore.push(client.database, 'warns', interaction.guildId, { userId: user.id, modId: interaction.user.id, reason });
        modstore.push(client.database, 'cases', interaction.guildId, { action: 'warn', userId: user.id, modId: interaction.user.id, reason });
        const total = modstore.all(client.database, 'warns', interaction.guildId).filter(w => w.userId === user.id).length;
